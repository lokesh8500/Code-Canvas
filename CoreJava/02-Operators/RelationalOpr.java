class RelationalOpr
{
	public static void main(String args[])
	{
		
		int a = 50;
		int b = 60;
		// always returns true and false
		System.out.println(a > b);
		System.out.println(a >= b);
		System.out.println(a < b);
		System.out.println(a <= b);
		System.out.println(a == b);
		System.out.println(a != b);
		
 	}
}